// ------------------------------------------------------------------ invoices / payments (staff have no financial read access)
export async function getInvoice(tx: Queryable, id: string) {
  const { customerId } = await scope(tx, "invoice.read.any", "invoice.read.own");
  if (!isUuid(id)) return null;
  const inv = (await tx.query(`SELECT * FROM invoices WHERE id = $1 AND ($2::uuid IS NULL OR customer_id = $2)`, [id, customerId])).rows[0];
  if (!inv) return null;
  const lines = (await tx.query(`SELECT * FROM invoice_lines WHERE invoice_id = $1 ORDER BY line_no`, [id])).rows;
  return { ...inv, lines };
}
export async function listInvoices(tx: Queryable, filter: { customerId?: string; limit?: number } = {}) {
  const { customerId } = await scope(tx, "invoice.read.any", "invoice.read.own");
  const cid = customerId ?? (filter.customerId && isUuid(filter.customerId) ? filter.customerId : null);
  if (customerId === null && filter.customerId && !cid) return [];
  return (await tx.query(`SELECT * FROM invoices WHERE ($1::uuid IS NULL OR customer_id = $1) ORDER BY created_at DESC, id LIMIT $2`, [cid, Math.min(Math.max(Number(filter.limit) || 50, 1), 500)])).rows;
}
export async function getInvoicePayments(tx: Queryable, invoiceId: string) {
  const { customerId } = await scope(tx, "invoice.read.any", "invoice.read.own");
  if (!isUuid(invoiceId)) return null;
  const owned = (await tx.query(`SELECT 1 FROM invoices WHERE id = $1 AND ($2::uuid IS NULL OR customer_id = $2)`, [invoiceId, customerId])).rows[0];
  if (!owned) return null;
  return (await tx.query(`SELECT id, amount_ghs, status, method, source, created_at, voided_at FROM payments WHERE invoice_id = $1 ORDER BY created_at, id`, [invoiceId])).rows;
}
